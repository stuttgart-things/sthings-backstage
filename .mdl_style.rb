# Markdown rules for mdl in the Repository Linting check. The blueprint
# module's built-in .mdlrc is markdownlint JSON, which mdl does not read,
# so its intended exclusions (line length, inline HTML, first-line heading)
# never applied; they are set here in mdl's own format.
all
exclude_rule 'MD013' # line length
exclude_rule 'MD033' # inline HTML
exclude_rule 'MD041' # first line must be a heading
# Ordered lists numbered 1. 2. 3. (as prettier writes them).
rule 'MD029', :style => :ordered
# CHANGELOG.md (semantic-release) repeats "### Features" per version.
rule 'MD024', :allow_different_nesting => true
# Blank lines are prettier's job in hand-written files; CHANGELOG.md is
# generated by semantic-release with double blank lines.
exclude_rule 'MD012'
# Questions are fine as headings ("Why both scaffolder and catalog?").
rule 'MD026', :punctuation => '.,;:!'
# Bold labels ("**"Bad credentials"**" above a list) are intended, not
# headings in disguise.
exclude_rule 'MD036'
